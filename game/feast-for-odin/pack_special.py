"""Pack the special tiles into a board and write special_layout.scad.

Run: just python game/feast-for-odin/pack_special.py [forge_w] [others_w]
(currently 66 229)

The forge section sits left of the others, side by side.

Greedy bottom-left packing on a 0.5 mm raster. Each tile's footprint is its
cells grown by the pocket clearance plus half a wall, and includes its finger
notch, so neighbors never cut into each other. Tiles may rotate, not flip.
"""

import sys
