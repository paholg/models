"""Make FullControl G-code previewable in Snapmaker Orca.

Snapmaker Orca's viewer only reads tool/filament info from G-code it thinks it
generated: a "generated by Snapmaker Orca" header plus a config block with at
least 80 recognized settings (see GCodeProcessor.cpp / Config.cpp in
Snapmaker/OrcaSlicer v2.4.1).

Profiles come from the Snapmaker Orca package, via $SNAPMAKER_ORCA_PROFILES
(set by the nix dev shell).
"""

import json
import os
import re
from pathlib import Path

from .settings import Settings

HEADER = "; generated by Snapmaker Orca (compatible header from FullControl)"
VENDOR = "Snapmaker"
# Only used to get past the viewer's 80-setting minimum.
PROCESS_PROFILE = "fdm_process_U1_0.20"

_PLAIN = re.compile(r"^-?[\d.]+%?$|^-?[\d.]+x-?[\d.]+$")  # number, percent, or point
_SKIP = {"name", "inherits", "from", "type", "setting_id", "instantiation", "version"}


def _profiles_dir() -> Path:
    try:
        return Path(os.environ["SNAPMAKER_ORCA_PROFILES"])
    except KeyError:
        raise RuntimeError(
            "SNAPMAKER_ORCA_PROFILES not set; run inside `nix develop`"
        ) from None


def _load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def profile(name: str) -> dict:
    """Resolve a vendor profile by name, following `inherits` like Orca does.

    Doesn't include Orca's built-in defaults, so keys a profile never sets are absent.
    """
    root = _profiles_dir()
    index = _load_json(root / f"{VENDOR}.json")
    paths = {
        e["name"]: e["sub_path"]
        for k, v in index.items()
        if k.endswith("_list")
        for e in v
    }
    d = _load_json(root / VENDOR / paths[name])
    base = profile(d["inherits"]) if d.get("inherits") else {}
    return {**base, **d}


def machine_profile(s: Settings) -> dict:
    return profile(f"Snapmaker U1 ({s.nozzle_diameter} nozzle)")


def config_block(s: Settings) -> str:
    cfg = {**machine_profile(s), **profile(PROCESS_PROFILE)}
    lines = []
    for k, v in cfg.items():
        if k in _SKIP:
            continue
        if isinstance(v, list):
            # Text lists use a different separator; skip any we can't be sure of.
            if not all(_PLAIN.match(str(x)) for x in v):
                continue
            v = ",".join(map(str, v))
        v = str(v)
        if "\n" in v or "\\n" in v:
            continue
        lines.append(f"; {k} = {v}")
    fs = s.filaments
    lines += [
        f"; filament_diameter = {','.join(str(f.diameter) for f in fs)}",
        f"; filament_density = {','.join(str(f.density) for f in fs)}",
        f"; filament_type = {';'.join(f.type for f in fs)}",
        f"; filament_colour = {';'.join(f.color for f in fs)}",
        f"; extruder_colour = {';'.join(f.color for f in fs)}",
    ]
    return "\n".join(["; CONFIG_BLOCK_START", *lines, "; CONFIG_BLOCK_END"])
